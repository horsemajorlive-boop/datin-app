// Заглушка "живого собеседника".
// Пока нет сервера и других реальных людей, на каждое ваше сообщение
// приходит случайный ответ из этого списка (через ~1.2 сек).
// Позже это заменят настоящие сообщения от собеседника через backend.

const REPLIES = [
  'Привет! Рад(а), что мы мэтчнулись 🙂',
  'О, у нас совпали интересы!',
  'Как проходит твой день?',
  'Чем обычно занимаешься на выходных?',
  'Полностью согласен(на) 😄',
  'Расскажи о себе побольше!',
  'Интересно! А что ещё?',
  'Ха-ха, точно 😂',
  'Может, как-нибудь сходим за кофе?',
  'Что любишь смотреть или слушать?',
];

export function randomReply() {
  return REPLIES[Math.floor(Math.random() * REPLIES.length)];
}
