// Плоский список всех интересов каталога.
export const INTEREST_OPTIONS = INTEREST_CATEGORIES.flatMap((cat) =>
  cat.items.map((label) => ({ label, categoryId: cat.id, icon: cat.icon }))
);

// Словарь "название -> ключ иконки" (строим один раз).
const ICON_BY_LABEL = Object.fromEntries(
  INTEREST_OPTIONS.map((o) => [o.label.toLowerCase(), o.icon])
);

export function interestIconKey(label) {
  return ICON_BY_LABEL[String(label).toLowerCase()] ?? 'tag';
}
