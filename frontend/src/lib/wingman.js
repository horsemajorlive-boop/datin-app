// "ИИ-помощник" для раскачки диалога.
//
// Сейчас это набор правил (эвристик), а не настоящая нейросеть.
// Позже getSuggestions() можно заменить на запрос к языковой модели —
// вход (кто с кем, история) и выход (массив фраз) останутся такими же.

// Общие интересы двух анкет (сравнение без учёта регистра).
export function commonInterests(me, them) {
  const mine = new Set((me?.interests || []).map((s) => s.toLowerCase()));
  return (them?.interests || []).filter((i) => mine.has(i.toLowerCase()));
}

const GENERIC_OPENERS = [
  'Привет! Что зацепило тебя в моей анкете?',
  'Опиши свои идеальные выходные тремя эмодзи',
  'Кофе, чай или сразу вино? ☕🍷',
  'Что подняло тебе настроение сегодня?',
];

// Затравка на основе конкретного общего интереса.
const OPENER_BY_INTEREST = {
  горы: 'У нас обоих горы — какой был лучший поход?',
  кофе: 'Вижу, ты за кофе. Любимая кофейня в городе?',
  настолки: 'Настолки! Во что рубишься чаще всего?',
  кино: 'Кино у обоих в списке — последний фильм, который зашёл?',
  музыка: 'Что сейчас в плейлисте на репите?',
  путешествия: 'Куда следующая поездка в планах?',
  спорт: 'Что за спорт? Ищу компанию для тренировок 💪',
  бег: 'Тоже бегаешь? Какая дистанция любимая?',
  море: 'Море! Ты больше про пляж или про сёрф?',
  книги: 'Что читаешь сейчас?',
  фотография: 'На что снимаешь — телефон или камера?',
  йога: 'Йога — утренняя practice или вечерняя?',
  кошки: 'Показывай кота 🐈',
  собаки: 'Показывай собакена 🐕',
};

function interestOpeners(common) {
  return common.map(
    (i) =>
      OPENER_BY_INTEREST[i.toLowerCase()] ||
      `У нас общий интерес — «${i}». Расскажи про это?`
  );
}

export function getSuggestions({ myProfile, match, messages }) {
  const common = commonInterests(myProfile, match);

  // 1. Переписки ещё нет — предлагаем, с чего начать (сначала по общим интересам).
  if (messages.length === 0) {
    return dedupe([
      ...interestOpeners(common).slice(0, 2),
      ...GENERIC_OPENERS,
    ]).slice(0, 4);
  }

  const last = messages[messages.length - 1];

  // 2. Последними написали мы — предлагаем, чем продолжить.
  if (last.from === 'me') {
    return dedupe([
      'Кстати, чем занимаешься по жизни?',
      common[0]
        ? `А что тебе больше всего в «${common[0]}»?`
        : 'Расскажи что-нибудь неожиданное о себе',
      'Как насчёт созвониться на этой неделе?',
    ]).slice(0, 4);
  }

  // 3. Отвечаем на сообщение собеседника — смотрим на его текст.
  const text = last.text.toLowerCase();
  const out = [];

  if (text.includes('?')) {
    out.push('Хороший вопрос! Расскажу — но сначала ты 😄');
  }
  if (/(привет|хай|здоров|добрый)/.test(text)) {
    out.push('Привет-привет! Рад(а), что списались 🙂');
  }
  if (/(кофе|встрет|свидан|погул|сходим|кино|бар|прогул)/.test(text)) {
    out.push('Я только за. Давай выберем день?');
  }
  out.push('Согласен(на)! А у тебя как с этим?');
  if (common[0]) {
    out.push(`Раз оба любим «${common[0]}» — может, сходим вместе?`);
  }

  return dedupe(out).slice(0, 4);
}

// Убирает повторы, сохраняя порядок.
function dedupe(list) {
  return [...new Set(list)];
}
